const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('connector', {
  state: () => ipcRenderer.invoke('state'),
  startDiagnostic: input => ipcRenderer.invoke('diagnostics:start',input),
  writeDiagnostic: (id,data,encoding) => ipcRenderer.invoke('diagnostics:write',id,data,encoding),
  stopDiagnostic: id => ipcRenderer.invoke('diagnostics:stop',id),
  setCastCollaboration: (castId,peerId,enabled) => ipcRenderer.invoke('team:collaborate',castId,peerId,enabled),
  writeLive: (id,castId,data) => ipcRenderer.invoke('team:live-input',id,castId,data),
  saveForward: (input,id) => ipcRenderer.invoke('forward:save',input,id),
  removeForward: id => ipcRenderer.invoke('forward:remove',id),
  startForward: id => ipcRenderer.invoke('forward:start',id),
  stopForward: id => ipcRenderer.invoke('forward:stop',id),
  setTerminalFullscreen: enabled => ipcRenderer.invoke('terminal:fullscreen', enabled),
  persistShared: (kind, id) => ipcRenderer.invoke('team:persist', kind, id),
  copyServer: id => ipcRenderer.invoke('server:copy', id),
  copyVPN: id => ipcRenderer.invoke('vpn:copy', id),
  startTeamServer: input => ipcRenderer.invoke('team:start', input),
  stopTeamServer: () => ipcRenderer.invoke('team:stop'),
  createTeamKey: input => ipcRenderer.invoke('team:create-key', input),
  updateTeamKey: (id, input) => ipcRenderer.invoke('team:update-key', id, input),
  revokeTeamKey: (id, remove) => ipcRenderer.invoke('team:revoke', id, remove),
  addTeamServer: input => ipcRenderer.invoke('team:add-client', input),
  setTeamServer: (id, enabled, remove) => ipcRenderer.invoke('team:set-client', id, enabled, remove),
  castTerminal: (sessionId, keyId) => ipcRenderer.invoke('team:cast', sessionId, keyId),
  stopCast: id => ipcRenderer.invoke('team:stop-cast', id),
  watchCast: (id, castId) => ipcRenderer.invoke('team:watch', id, castId),
  copyInvitation: value => ipcRenderer.invoke('team:copy-invite', value),
  saveServer: (input, id) => ipcRenderer.invoke('server:save', input, id),
  routeServers: (ids, mode, vpnId) => ipcRenderer.invoke('server:route-many', ids, mode, vpnId),
  removeServer: id => ipcRenderer.invoke('server:remove', id),
  chooseKey: () => ipcRenderer.invoke('key:choose'),
  openSSH: (id, cols, rows) => ipcRenderer.invoke('ssh:open', id, cols, rows),
  openSSHMany: ids => ipcRenderer.invoke('ssh:open-many', ids),
  fileState: () => ipcRenderer.invoke('files:state'),
  openFiles: id => ipcRenderer.invoke('files:open', id),
  closeFiles: id => ipcRenderer.invoke('files:close', id),
  listFiles: (id, directory) => ipcRenderer.invoke('files:list', id, directory),
  makeDirectory: (id, directory, name) => ipcRenderer.invoke('files:mkdir', id, directory, name),
  chooseLocalFolder: () => ipcRenderer.invoke('files:local-folder'),
  transferFiles: input => ipcRenderer.invoke('files:transfer', input),
  cancelTransfer: id => ipcRenderer.invoke('files:cancel', id),
  writeSSH: (id, data) => ipcRenderer.invoke('ssh:write', id, data),
  resizeSSH: (id, cols, rows) => ipcRenderer.invoke('ssh:resize', id, cols, rows),
  closeSSH: id => ipcRenderer.invoke('ssh:close', id),
  runBatch: input => ipcRenderer.invoke('batch:run', input),
  cancelBatch: id => ipcRenderer.invoke('batch:cancel', id),
  cancelBatchTarget: (id, serverId, remove = false) => ipcRenderer.invoke('batch:cancel-target', id, serverId, remove),
  writeBatch: (id, serverIds, data) => ipcRenderer.invoke('batch:input', id, serverIds, data),
  resizeBatch: (id, serverId, cols, rows) => ipcRenderer.invoke('batch:resize', id, serverId, cols, rows),
  enableAI: enabled => ipcRenderer.invoke('ai:enable', enabled),
  saveVPN: (input, id) => ipcRenderer.invoke('vpn:save', input, id),
  removeVPN: id => ipcRenderer.invoke('vpn:remove', id),
  startVPN: id => ipcRenderer.invoke('vpn:start', id),
  stopVPN: id => ipcRenderer.invoke('vpn:stop', id),
  saveRoute: (input, id) => ipcRenderer.invoke('route:save', input, id),
  removeRoute: id => ipcRenderer.invoke('route:remove', id),
  previewRoute: id => ipcRenderer.invoke('route:preview', id),
  exportProfiles: options => ipcRenderer.invoke('backup:export', options),
  openImport: () => ipcRenderer.invoke('backup:open'),
  previewImport: (token, passphrase) => ipcRenderer.invoke('backup:preview', token, passphrase),
  cancelImport: token => ipcRenderer.invoke('backup:cancel', token),
  applyImport: (token, enableRules) => ipcRenderer.invoke('backup:apply', token, enableRules),
  copyConfig: () => ipcRenderer.invoke('config:copy'),
  copyTerminal: value => ipcRenderer.invoke('terminal:copy', value),
  readTerminalClipboard: () => ipcRenderer.invoke('terminal:clipboard'),
  decideAI: (id, approve) => ipcRenderer.invoke('ai:decide', id, approve),
  onEvent: callback => { const listener = (_event, data) => callback(data); ipcRenderer.on('connector:event', listener); return () => ipcRenderer.removeListener('connector:event', listener); }
});
