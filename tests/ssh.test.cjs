const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { Store } = require('../electron/store.cjs');
const { SSH } = require('../electron/ssh.cjs');
const { startServer, key } = require('./ssh-fixture.cjs');
test('real SSH: trust, PTY, exec, exit code, cap, timeout and changed host key', async t => {
  const fixture = await startServer();
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'connector-ssh-'));
  const vault = { available: () => true, encrypt: s => Buffer.from(s).toString('base64'), decrypt: s => Buffer.from(s, 'base64').toString() };
  const store = await Store.open(directory, vault);
  const server = store.put({ name: 'Local test', host: '127.0.0.1', port: fixture.port, username: 'tester', auth: 'password', secret: 'test-password' });
  let approvals = 0, allow = false; const events = [];
  const ssh = new SSH(store, vault, async () => { approvals++; return allow; }, (type, data) => events.push({ type, ...data }));
  t.after(async () => { ssh.closeAll(); await fixture.close(); store.db.close(); fs.rmSync(directory, { recursive: true, force: true }); });
  await assert.rejects(() => ssh.open(server.id), /verification failed/);
  assert.equal(store.fingerprint(`[127.0.0.1]:${fixture.port}`), undefined);
  allow = true;
  const opened = await ssh.open(server.id);
  ssh.write(opened.sessionId, 'hello terminal'); ssh.resize(opened.sessionId, 100, 30);
  await new Promise(resolve => setTimeout(resolve, 120));
  assert.ok(events.some(e => e.data?.includes('hello terminal'))); ssh.close(opened.sessionId);
  const credential = store.get(server.id), signal = new AbortController().signal;
  let output = '';
  const successful = await ssh.exec(credential, 'uptime', 5, signal, data => output += data);
  assert.equal(successful.exitCode, 0); assert.equal(successful.status, 'succeeded'); assert.match(output, /executed: uptime/);
  assert.equal(approvals, 2, 'pinned host needs no further trust prompt');
  const failed = await ssh.exec(credential, 'fail-test', 5, signal, () => {}); assert.equal(failed.exitCode, 7); assert.equal(failed.status, 'failed');
  let bytes = 0;
  const large = await ssh.exec(credential, 'large-output', 5, signal, data => bytes += Buffer.byteLength(data)); assert.equal(large.truncated, true); assert.equal(bytes, 256 * 1024);
  const timeout = await ssh.exec(credential, 'sleep-forever', 0.15, signal, () => {}); assert.equal(timeout.status, 'timed-out');
  let interactiveOutput = '', control;
  const interactive = ssh.exec(credential, 'confirm-test', 5, signal, chunk => {
    interactiveOutput += chunk;
    if (interactiveOutput.includes('[y/N]') && control) control.write('y\r');
  }, { interactive: true, onReady: c => { control = c; c.resize(110, 18); } });
  assert.equal((await interactive).status, 'succeeded'); assert.match(interactiveOutput, /Confirmed/);
  const noPTY = await ssh.exec(credential, 'confirm-test', 5, signal, () => {});
  assert.equal(noPTY.exitCode, 2, 'the fixture requires an actual PTY for interactive confirmation');
  const pinned = store.fingerprint(`[127.0.0.1]:${fixture.port}`);
  const changedKey = require('ssh2').utils.parseKey(key()).getPublicSSH();
  assert.equal(await ssh.checkHost(credential, changedKey), false); assert.equal(store.fingerprint(`[127.0.0.1]:${fixture.port}`), pinned);
});
