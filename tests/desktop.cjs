function startMcp() {
  const bridgePath = process.env.CONNECTOR_EXECUTABLE ? path.join(path.dirname(executablePath), 'resources/app.asar/electron/bridge.cjs') : path.join(root, 'electron/bridge.cjs');
  bridge = spawn(executablePath, [bridgePath, directory], { env: { ...env, ELECTRON_RUN_AS_NODE: '1' }, windowsHide: true, stdio: ['pipe', 'pipe', 'pipe'] });
  const pending = new Map(); let id = 0;
  readline.createInterface({ input: bridge.stdout }).on('line', line => {
    try { const message = JSON.parse(line); const resolve = pending.get(message.id); if (resolve) { pending.delete(message.id); resolve(message); } } catch {}
  });
  bridge.stderr.on('data', () => {});
  return (method, params) => new Promise((resolve, reject) => {
    const requestId = ++id;
    const timer = setTimeout(() => { pending.delete(requestId); reject(new Error(`MCP timeout: ${method}`)); }, 15000);
    pending.set(requestId, value => { clearTimeout(timer); resolve(value); });
    bridge.stdin.write(JSON.stringify({ jsonrpc: '2.0', id: requestId, method, params }) + '\n');
  });
}
